function drawTableOfContents(doc, document) {

  doc
    .font("Helvetica-Bold")
    .fontSize(30)
    .fillColor(BRAND.colors.primary)
    .text("Table of Contents");

  doc.moveDown(1.5);

  const sections = [
  { no: 1, title: "Executive Summary", page: 3 },
  { no: 2, title: "Detailed Analysis", page: 3 },
  { no: 3, title: "Recommendations", page: 4 },
  { no: 4, title: "Sources", page: 4 }
];

  doc
    .font("Helvetica")
    .fontSize(16)
    .fillColor(BRAND.colors.text);

  sections.forEach((section, index) => {

  const page = section.page || index + 3;

  doc.text(
    `${section.no}. ${section.title}`,
    {
      continued: true
    }
  );

  doc.text(
    ` ........................................ ${page}`,
    {
      align: "right"
    }
  );

  doc.moveDown(0.7);

});

  doc.addPage();

}
