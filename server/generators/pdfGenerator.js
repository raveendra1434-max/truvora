import PDFDocument from "pdfkit";
import fs from "fs";
import path from "path";
import { BRAND } from "../utils/branding.js";
import { prepareDocument } from "../documentGenerator.js";

function createPdf(filePath) {
  const doc = new PDFDocument({
    size: "A4",
    margins: {
      top: 70,
      bottom: 70,
      left: 20,
right: 20
    },
    bufferPages: false
  });

  doc.pipe(fs.createWriteStream(filePath));

  return doc;
}

function drawHeader(doc, reportId) {
  doc.save();

  doc.rect(0, 0, doc.page.width, 120)
     .fill(BRAND.colors.primary);

  doc.restore();

  doc
    .fillColor(BRAND.colors.white)
    .font("Helvetica-Bold")
    .fontSize(34)
    .text(BRAND.company.name, 0, 28, {
      align: "center"
    });

  doc
    .fillColor(BRAND.colors.white)
    .font("Helvetica")
    .fontSize(15)
    .text(BRAND.company.fullName, {
      align: "center"
    });

  doc.moveDown(0.3);

  doc
    .fillColor(BRAND.colors.white)
    .fontSize(12)
    .text(BRAND.company.slogan, {
      align: "center"
    });

  doc.moveDown(2);

  doc
    .fillColor(BRAND.colors.text)
    .font("Helvetica-Bold")
    .fontSize(24)
    .text(BRAND.document.title, {
      align: "center"
    });

  doc.moveDown();

  doc
    .font("Helvetica")
    .fontSize(11)
    .fillColor(BRAND.colors.lightText)

  doc.text(`Report ID : ${reportId}`);
  doc.text(`Generated : ${new Date().toLocaleString()}`);
  doc.text("AI Engine : Trulexity AI");
  doc.text("Status : Completed");

  doc.moveDown();
}
function drawSectionTitle(doc, title) {
  doc.moveDown(0.3);

  doc
    .font("Helvetica-Bold")
    .fontSize(18)
    .fillColor(BRAND.colors.primary)
    .text(title);

  doc.moveDown(0.4);

  doc
    .moveTo(doc.page.margins.left, doc.y)
.lineTo(doc.page.width - doc.page.margins.right, doc.y)
    .strokeColor(BRAND.colors.accent)
    .lineWidth(1)
    .stroke();

  doc.moveDown(0.3);
}

function drawParagraph(doc, text) {

  text = String(text || "")
  .replace(/✅\s*/g, "")
  .replace(/📖\s*/g, "")
  .replace(/❌\s*/g, "")
  .replace(/🔍\s*/g, "")
  .replace(/📌\s*/g, "")
  .replace(/🎯\s*/g, "")
  .replace(/💡\s*/g, "")
  .replace(/\r/g, "")
  .replace(/\n{3,}/g, "\n\n")
  .replace(/[ \t]{2,}/g, " ")
  .trim();

  doc
  .font("Helvetica")
  .fontSize(12)
  .fillColor(BRAND.colors.text);

console.log("DRAWING PARAGRAPH");
console.log("Current Y:", doc.y);
console.log("Text length:", text.length);

doc.text(
  text,
  doc.page.margins.left,
  doc.y,
  {
    width: doc.page.width - doc.page.margins.left - doc.page.margins.right,
    align: "left",
    lineGap: 5,
  }
);
console.log("After text Y:", doc.y);
  doc.moveDown(0.4);
}
function drawFooter(doc, metadata) {

  const range = doc.bufferedPageRange();

  for (let i = 0; i < range.count; i++) {

    doc.switchToPage(i);

    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor("#777777");

    doc.text(
      `Generated by Trulexity AI`,
      60,
      doc.page.height - 40
    );

    doc.text(
      `Page ${i + 1} of ${range.count}`,
      0,
      doc.page.height - 40,
      {
        align: "right"
      }
    );
  }

}


